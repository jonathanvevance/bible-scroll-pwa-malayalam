"""Prepare the PWA's generated assets from the iOS project's sources of truth.

- books.js       from BibleCore's BookCatalog.swift (66 rows, same names and slugs)
- mal1910.json   Malayalam Sathyavedapusthakam 1910 (contemporary orthography), converted
                 from eBible.org's USFM. CC BY-SA 4.0, The Free Bible Foundation.
- icons/*.png    drawn here, so no image tooling is needed

Usage: python3 build.py [path/to/bible-scroll]   (default: ../bible-scroll)
"""

import io
import json
import math
import re
import struct
import sys
import urllib.request
import zipfile
import zlib
from pathlib import Path

PWA = Path(__file__).resolve().parent
IOS = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else PWA.parent / "bible-scroll"
CATALOG = IOS / "BibleCore/Sources/BibleCore/BookCatalog.swift"
MAL_USFM = "https://ebible.org/Scriptures/mal2015_usfm.zip"

ROW = re.compile(
    r'row\((\d+), "(\w+)", "(\w+)", "([^"]+)",(?: bsb: "([^"]+)",)? slug: "(\w+)", chapters: (\d+)\)'
)


def build_books() -> None:
    books = []
    for m in ROW.finditer(CATALOG.read_text()):
        order, usfm, osis, name, bsb, slug, chapters = m.groups()
        books.append({
            "order": int(order), "usfm": usfm, "osis": osis, "name": name,
            "bsbName": bsb or name, "slug": slug, "chapters": int(chapters),
        })
    assert [b["order"] for b in books] == list(range(1, 67)), "catalog parse failed"
    (PWA / "books.js").write_text(
        "// Generated by pwa/build.py from BookCatalog.swift. Do not edit.\n"
        f"export const BOOKS = {json.dumps(books, separators=(',', ':'))};\n"
    )


# Notes (\f, \x) and figures are dropped whole; other character markers keep their text.
NOTE = re.compile(r"\\(f|x|fig) .*?\\\1\*", re.S)
CHAR = re.compile(r"\\\+?[a-z]+\d*(\*| ?)")
# Lines that are not verse text: titles, headings, Psalm superscriptions, acrostic letters.
SKIP = re.compile(r"\\(id|h|toc\d|mt\d|ms\d|s\d|r|d|qa)\b")


def build_malayalam() -> None:
    usfm = {}
    # eBible.org refuses urllib's default User-Agent.
    request = urllib.request.Request(MAL_USFM, headers={"User-Agent": "curl/8"})
    with zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(request).read())) as z:
        for name in z.namelist():
            if name.endswith(".usfm"):
                text = z.read(name).decode("utf-8-sig")
                usfm[re.match(r"\\id (\w+)", text).group(1)] = text

    order = [b["usfm"] for b in json.loads((PWA / "books.js").read_text().split("= ", 1)[1].rstrip(";\n"))]
    books = []
    for code in order:
        chapters, verse = [], None
        for line in NOTE.sub("", usfm[code]).splitlines():
            line = line.strip()
            if not line or SKIP.match(line):
                continue
            if m := re.match(r"\\c (\d+)", line):
                chapters.append([])
                assert len(chapters) == int(m.group(1)), f"{code} chapter order"
                verse = None
                continue
            if m := re.match(r"\\v (\d+)\s*(.*)", line):
                verse = int(m.group(1))
                line = m.group(2)
                verses = chapters[-1]
                verses.extend([""] * (verse - len(verses)))
            if verse is None:
                continue
            text = re.sub(r"\s+", " ", CHAR.sub("", line)).strip()
            if text:
                chapters[-1][verse - 1] = f"{chapters[-1][verse - 1]} {text}".strip()
        books.append(chapters)

    data = {"translation": "Sathyavedapusthakam 1910", "books": books}
    (PWA / "mal1910.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))


def png(size: int) -> bytes:
    """A warm off-white Latin cross on a deep charcoal tile.

    Opaque and full-bleed: iOS rounds the corners itself. The cross stays inside the
    central 80%, so Android can crop it as a maskable icon.
    """
    top, bottom, cross, glow = (40, 40, 44), (12, 12, 14), (244, 238, 224), (120, 96, 60)
    centre, bar = size / 2, size * 0.078
    stem_top, stem_bottom = size * 0.20, size * 0.80
    arm_y, arm_half = size * 0.38, size * 0.20  # crossbar a third of the way down

    def inside(x: float, y: float) -> bool:
        stem = abs(x - centre) <= bar / 2 and stem_top <= y <= stem_bottom
        arm = abs(y - arm_y) <= bar / 2 and abs(x - centre) <= arm_half
        return stem or arm

    samples = [(i + 0.5) / 4 for i in range(4)]  # 4x4 supersampling for smooth edges
    rows = []
    for y in range(size):
        t = y / (size - 1)
        base = [a + (b - a) * t for a, b in zip(top, bottom)]
        row = bytearray([0])
        for x in range(size):
            # A soft warm glow centred where the arms meet.
            d2 = ((x - centre) ** 2 + (y - arm_y) ** 2) / (size * 0.32) ** 2
            g = 0.55 * math.exp(-d2)
            bg = [b + (w - b) * g for b, w in zip(base, glow)]
            cover = sum(inside(x + sx, y + sy) for sx in samples for sy in samples) / 16
            row += bytes(round(b + (c - b) * cover) for b, c in zip(bg, cross))
        rows.append(bytes(row))
    raw = zlib.compress(b"".join(rows), 9)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", raw) + chunk(b"IEND", b"")


def write_icons() -> None:
    # Renamed when the design changes: iOS and the service worker cache icons by URL.
    for size in (180, 192, 512):
        (PWA / "icons" / f"cross-{size}.png").write_bytes(png(size))


def main() -> None:
    build_books()
    build_malayalam()
    (PWA / "icons").mkdir(exist_ok=True)
    write_icons()
    print("books.js, mal1910.json, icons written to", PWA)


if __name__ == "__main__":
    main()
